def _normalize(name):
    """归一化期刊名：去除括号变体、标点、空格，便于严格比较"""
    if not name:
        return ""
    n = name.strip()
    n = n.replace("《", "").replace("》", "")
    # 括号变体统一：全角/半角、圆括号/书名号
    n = n.replace("（", "(").replace("）", ")").replace("【", "(").replace("】", ")")
    # 去除常见标点
    n = n.replace("·", "").replace(".", "").replace(" ", "").replace("　", "")
    return n


# 归一化后的CSSCI名单（一次性构建，供严格匹配用）
_NORM_JOURNALS = {_normalize(j) for j in CSSCI_JOURNALS}

# 已知的别名/变体映射（期刊改名或常见异名）——只放有把握的
_ALIASES = {
    "中国人口资源与环境": "中国人口·资源与环境",
    "中国人口.资源与环境": "中国人口·资源与环境",
}


def is_cssci(journal_name):
    """判断期刊是否在CSSCI名单中（严格匹配：精确命中或归一化后命中，禁止宽松子串）

    2026-08-07 修复：旧版 `name in j or j in name` 子串匹配导致：
    - 《国际金融》被《国际金融研究》误匹配（"国际金融" in "国际金融研究"）
    - 《重庆交通大学学报（社会科学版）》被名单中的"社会科学"短词误匹配
    - 新闻稿/报纸名若含名单短词也可能绕过过滤
    现改为：精确匹配 → 别名映射 → 归一化匹配（去标点/括号统一），一律禁止子串。
    """
    if not journal_name:
        return False
    name = journal_name.strip().replace("《", "").replace("》", "")
    # 1. 精确匹配
    if name in CSSCI_JOURNALS:
        return True
    # 2. 别名映射
    if name in _ALIASES:
        return _ALIASES[name] in CSSCI_JOURNALS
    # 3. 归一化匹配（处理括号变体）
    norm = _normalize(name)
    if norm and norm in _NORM_JOURNALS:
        return True
    return False


