def is_cssci(journal_name):
    """判断期刊是否在CSSCI名单中"""
    if not journal_name:
        return False
    name = journal_name.strip().replace("《", "").replace("》", "")
    if name in CSSCI_JOURNALS:
        return True
    # 模糊匹配：名单中的期刊名是name的子串或反之
    for j in CSSCI_JOURNALS:
        if name in j or j in name:
            return True
    return False

